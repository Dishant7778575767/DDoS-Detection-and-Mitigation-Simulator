logger = logging.getLogger("sentrix.simulator")

_RUN_EVALUATORS: dict[str, tuple[ScenarioEngine, TickEvaluator, int]] = {}

ALLOWED_SPEEDS: set[float] = {1.0, 10.0, 100.0}
MAX_CONCURRENT_RUNS: int = 2
MAX_DURATION_TICKS: int = 3600
DEFAULT_RETENTION_MAX_RUNS: int = 50

DISCLAIMER_TEXT: str = (
    "DISCLAIMER: This report is generated by SENTRIX, a defensive synthetic DDoS simulator. "
    "All traffic, metrics, and actions are 100% simulated in-memory calculations. "
    "No real network packets were transmitted, no real hosts were targeted, and no host "
    "firewall or network interfaces were modified. SENTRIX is not a production protection service."
)


class ConcurrencyLimitExceededError(RuntimeError):
    """Raised when maximum allowed active simulation runs are already executing."""


class InvalidControlTransitionError(ValueError):
    """Raised when an illegal run control action is attempted (e.g. resuming a completed run)."""


class IncompatibleRunComparisonError(ValueError):
    """Raised when attempting to compare incompatible simulation runs."""


class SimulationRunManager:
    """Orchestrates persistent simulation execution, virtual clock, and run lifecycle."""

    def __init__(self, session: Session) -> None:
        self.session = session
        self.repo = SimulationRunRepository(session)
        self.audit_repo = AuditRepository(session)
        self.alert_repo = AlertRepository(session)
        self.mit_repo = MitigationRepository(session)
        self.obs_repo = ObservationRepository(session)
        self.det_repo = DetectionRepository(session)

    def create_run(
        self,
        config: ScenarioConfig,
        victim_config: VirtualVictimConfig | None = None,
        speed_multiplier: float = 1.0,
        user_id: str = "demo_user",
    ) -> SimulationRunModel:
        """Create and persist a new simulation run in 'created' status."""
        if speed_multiplier not in ALLOWED_SPEEDS:
            raise ValueError(
                f"Invalid speed multiplier {speed_multiplier}. Allowed speeds: {sorted(ALLOWED_SPEEDS)}"
            )

        if config.total_ticks > MAX_DURATION_TICKS:
            raise ValueError(
                f"Requested total ticks ({config.total_ticks}) exceeds max permitted duration ({MAX_DURATION_TICKS})"
            )

        run_id = f"sim_{uuid.uuid4().hex[:12]}"
        victim_cfg = victim_config or VirtualVictimConfig()

        merged_config = {
            "scenario": config.model_dump(),
            "victim": victim_cfg.model_dump(),
        }

        # Enforce retention bounds before creating a new run
        self.repo.cleanup_old_runs(keep_max=DEFAULT_RETENTION_MAX_RUNS)

        run = self.repo.create_run(
            run_id=run_id,
            scenario_type=config.scenario_type.value,
            seed=config.seed,
            total_ticks=config.total_ticks,
            config=merged_config,
            scenario_version=config.scenario_version,
            speed_multiplier=speed_multiplier,
        )

        self.audit_repo.log(
            event_type="simulation_created",
            action="create_simulation_run",
            actor=user_id,
            details={
                "run_id": run_id,
                "scenario_type": config.scenario_type.value,
                "seed": config.seed,
                "total_ticks": config.total_ticks,
                "speed": speed_multiplier,
            },
        )
        return run

    def _check_concurrency_limit(self) -> None:
        active_count = self.repo.count_runs(status="running")
        if active_count >= MAX_CONCURRENT_RUNS:
            raise ConcurrencyLimitExceededError(
                f"Maximum concurrent runs limit reached ({MAX_CONCURRENT_RUNS}). "
                "Please pause or cancel an existing running simulation."
            )

    def start_or_resume_run(
        self, run_id: str, user_id: str = "demo_user"
    ) -> SimulationRunModel:
        """Transition run from 'created' or 'paused' to 'running'."""
        run = self.repo.get_run(run_id)
        if not run:
            raise ValueError(f"Simulation run {run_id} not found")

        if run.status in ("completed", "cancelled"):
            raise InvalidControlTransitionError(
                f"Cannot resume terminal run with status '{run.status}'"
            )

        if run.status == "running":
            return run

        self._check_concurrency_limit()

        new_status = "running"
        updated = self.repo.update_run_status(run_id, new_status)
        self.audit_repo.log(
            event_type="simulation_started",
            action="start_or_resume_simulation",
            actor=user_id,
            details={"run_id": run_id, "resumed_at_tick": run.current_tick},
        )
        return updated  # type: ignore[return-value]

    def pause_run(self, run_id: str, user_id: str = "demo_user") -> SimulationRunModel:
        """Pause an actively running simulation."""
        run = self.repo.get_run(run_id)
        if not run:
            raise ValueError(f"Simulation run {run_id} not found")

        if run.status != "running":
            raise InvalidControlTransitionError(
                f"Cannot pause run with status '{run.status}' (must be 'running')"
            )

        updated = self.repo.update_run_status(run_id, "paused")
        self.audit_repo.log(
            event_type="simulation_paused",
            action="pause_simulation",
            actor=user_id,
            details={"run_id": run_id, "paused_at_tick": run.current_tick},
        )
        return updated  # type: ignore[return-value]

    def cancel_run(self, run_id: str, user_id: str = "demo_user") -> SimulationRunModel:
        """Cancel a simulation run."""
        run = self.repo.get_run(run_id)
        if not run:
            raise ValueError(f"Simulation run {run_id} not found")

        if run.status in ("completed", "cancelled"):
            return run

        now = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        _RUN_EVALUATORS.pop(run_id, None)
        self.alert_repo.resolve_alerts_for_run(run_id)
        updated = self.repo.update_run_status(run_id, "cancelled", completed_at=now)
        self.audit_repo.log(
            event_type="simulation_cancelled",
            action="cancel_simulation",
            actor=user_id,
            details={"run_id": run_id, "cancelled_at_tick": run.current_tick},
        )
        return updated  # type: ignore[return-value]

    def reset_run(self, run_id: str, user_id: str = "demo_user") -> SimulationRunModel:
        """Reset a run back to tick 0 in 'created' state, clearing committed ticks."""
        run = self.repo.get_run(run_id)
        if not run:
            raise ValueError(f"Simulation run {run_id} not found")

        if run.status == "running":
            raise InvalidControlTransitionError(
                "Cannot reset an actively running simulation. Pause or cancel first."
            )

        # Delete existing tick records
        for t in list(run.ticks):
            self.session.delete(t)

        run.current_tick = 0
        run.status = "created"
        run.scorecard_json = None
        run.completed_at = None
        run.updated_at = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        _RUN_EVALUATORS.pop(run_id, None)
        self.alert_repo.resolve_alerts_for_run(run_id)
        self.session.commit()
        self.session.refresh(run)

        self.audit_repo.log(
            event_type="simulation_reset",
            action="reset_simulation",
            actor=user_id,
            details={"run_id": run_id},
        )
        return run

    def execute_single_step(
        self, run_id: str, user_id: str = "demo_user"
    ) -> tuple[SimulationRunModel, TickEvaluationResult | None]:
        """Advance the simulation by exactly one virtual tick."""
        run = self.repo.get_run(run_id)
        if not run:
            raise ValueError(f"Simulation run {run_id} not found")

        if run.status in ("completed", "cancelled"):
            return run, None

        if run.current_tick >= run.total_ticks:
            return run, None

        tick_idx = run.current_tick
        config_data = json.loads(run.config_json)
        scenario_cfg = ScenarioConfig(**config_data["scenario"])
        victim_cfg = VirtualVictimConfig(**config_data.get("victim", {}))

        # Re-use or initialize deterministic engine and evaluator with state continuity across ticks
        if run_id in _RUN_EVALUATORS and _RUN_EVALUATORS[run_id][2] == tick_idx - 1:
            engine, evaluator, _ = _RUN_EVALUATORS[run_id]
        else:
            engine = ScenarioEngine(scenario_cfg)
            evaluator = TickEvaluator(victim_config=victim_cfg)
            if tick_idx > 0:
                for past_t in range(tick_idx):
                    past_f, past_gt = engine.generate_tick(past_t)
                    evaluator.evaluate_tick(past_t, past_f, past_gt)

        features, ground_truth = engine.generate_tick(tick_idx)
        tick_result = evaluator.evaluate_tick(tick_idx, features, ground_truth)
        _RUN_EVALUATORS[run_id] = (engine, evaluator, tick_idx)

        # Commit tick to database
        vm = tick_result.victim_metrics
        self.repo.record_tick(
            run_id=run_id,
            tick=tick_idx,
            offered_legit_pps=vm.offered_legitimate_pps,
            offered_attack_pps=vm.offered_attack_pps,
            served_legit_pps=vm.served_legitimate_pps,
            dropped_legit_pps=vm.dropped_legitimate_pps,
            dropped_attack_pps=vm.dropped_attack_pps,
            latency_ms=vm.latency_ms,
            availability_pct=vm.availability_pct,
            prediction=tick_result.prediction.prediction,
            policy_action=tick_result.policy_action,
            active_mitigations_count=len(tick_result.active_mitigations),
        )

        # Update live sliding window aggregator with real simulated traffic
        now_ts = time.time()
        now_iso = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(now_ts))
        total_pps = vm.offered_legitimate_pps + vm.offered_attack_pps
        window_aggregator.add_observation(
            timestamp=now_ts,
            packet_count=int(total_pps),
            byte_count=int(total_pps * 128),
            syn_flags=int(
                features.get("Fwd PSH Flags", 0)
                or (total_pps * 0.1 if "syn" in run.scenario_type else 0)
            ),
            source_ip=scenario_cfg.target_ip,
        )

        # Ingest simulated network flow as live observation & detection records in database
        persisted_obs = self.obs_repo.create(
            source_id=f"probe_sim_{run.scenario_type}",
            timestamp=now_iso,
            window_seconds=1.0,
            feature_schema_version="1.0.0",
            features={**features, "pps": total_pps, "attack_pps": vm.offered_attack_pps},
            target_ip=scenario_cfg.target_ip,
        )

        event_id = f"det_{run_id}_{tick_idx}_{uuid.uuid4().hex[:6]}"
        persisted_det = self.det_repo.create(
            event_id=event_id,
            observation_id=persisted_obs.id,
            model_version="rf-1.0.0",
            feature_schema_version="1.0.0",
            prediction="ddos" if tick_result.policy_action != "monitor" and vm.offered_attack_pps > 0 else "benign",
            score_type="probability",
            score=round(float(features.get("Flow Bytes/s", 5000.0) / 10000.0), 3) if vm.offered_attack_pps > 0 else 0.05,
            traffic_threshold_exceeded=total_pps > 5000,
            policy_decision=tick_result.policy_action,
            mitigation_mode="simulation",
            timestamp=now_iso,
        )

        # Log audit events generated by evaluator
        for ev in tick_result.audit_events:
            self.audit_repo.log(
                event_type=ev.get("event_type", "simulation_event"),
                action=ev.get("action", "tick_eval"),
                actor=ev.get("actor", "simulator"),
                details={**ev.get("details", {}), "run_id": run_id, "tick": tick_idx},
            )

        # Persist triggered virtual mitigations to repository linked to detection
        now_dt = datetime.datetime.now(datetime.timezone.utc)
        for act in tick_result.new_actions:
            exp_sec = max(15, int(act.duration_ticks))
            exp_dt = now_dt + datetime.timedelta(seconds=exp_sec)
            self.mit_repo.create(
                detection_id=persisted_det.id,
                target_ip=act.target_ip,
                target_port=act.target_port,
                action_type=act.action_type,
                rate_limit_pps=int(act.attack_reduction_rate * 5000) or 5000,
                duration_seconds=exp_sec,
                status="active",
                mode="simulation",
                action_id=act.action_id,
                expires_at=exp_dt.strftime("%Y-%m-%dT%H:%M:%SZ"),
            )

        # Expire finished actions in repository
        for exp in tick_result.expired_actions:
            self.mit_repo.update_status(exp.action_id, "expired")

        # Persist alert when attack is ongoing linked to detection
        if (
            tick_result.policy_action in ("alert", "request_mitigation")
            and vm.offered_attack_pps > 0
            and (tick_idx % 3 == 0 or len(tick_result.new_actions) > 0)
        ):
            # Map severity realistically across all 4 distinct levels
            if tick_result.policy_action == "request_mitigation" and vm.availability_pct < 60:
                sev = "critical"
            elif vm.offered_attack_pps > 15000 or vm.availability_pct < 85:
                sev = "high"
            elif vm.offered_attack_pps > 4000:
                sev = "medium"
            else:
                sev = "low"

            self.alert_repo.create(
                detection_id=persisted_det.id,
                severity=sev,
                title=f"Simulation Attack: {run.scenario_type.upper()} ({sev.upper()})",
                description=f"Synthetic attack traffic detected on {scenario_cfg.target_ip}. Offered attack: {vm.offered_attack_pps:.0f} PPS.",
                source_id=f"sim_{run_id}_t{tick_idx}",
                timestamp=now_iso,
            )

        next_tick = tick_idx + 1
        self.repo.update_run_tick(run_id, next_tick)

        # Check for completion (ticks 0 to total_ticks - 1 run for exactly total_ticks duration)
        if next_tick >= run.total_ticks:
            _RUN_EVALUATORS.pop(run_id, None)
            self.alert_repo.resolve_alerts_for_run(run_id)
            # Reconstruct all ticks to compute final ground truth scorecard
            all_ticks = self._reconstruct_all_results(
                scenario_cfg, victim_cfg, run.total_ticks
            )
            scorecard = compute_scorecard(all_ticks)
            now = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
            run = self.repo.update_run_status(
                run_id,
                "completed",
                scorecard=scorecard.model_dump(),
                completed_at=now,
            )
            self.audit_repo.log(
                event_type="simulation_completed",
                action="complete_simulation",
                actor="simulator_engine",
                details={
                    "run_id": run_id,
                    "total_ticks": run.total_ticks,  # type: ignore[union-attr]
                    "scorecard": scorecard.model_dump(),
                },
            )
        else:
            self.session.refresh(run)

        return run, tick_result

    def _reconstruct_all_results(
        self,
        scenario_cfg: ScenarioConfig,
        victim_cfg: VirtualVictimConfig,
        total_ticks: int,
    ) -> list[TickEvaluationResult]:
        """Deterministically replay ticks to compute complete scorecard."""
        engine = ScenarioEngine(scenario_cfg)
        evaluator = TickEvaluator(victim_config=victim_cfg)
        results: list[TickEvaluationResult] = []
        for t in range(total_ticks):
            features, gt = engine.generate_tick(t)
            res = evaluator.evaluate_tick(t, features, gt)
            results.append(res)
        return results

    def compare_runs(self, run_ids: list[str]) -> dict[str, Any]:
        """Compare multiple runs by scenario, configuration, thresholds, and scorecard metrics."""
        if len(run_ids) < 2:
            raise ValueError("At least two run IDs are required for comparison")

        runs: list[SimulationRunModel] = []
        for r_id in run_ids:
            run = self.repo.get_run(r_id)
            if not run:
                raise ValueError(f"Simulation run {r_id} not found")
            runs.append(run)

        # Verify compatibility (PRD FR-23)
        base_scenario = runs[0].scenario_type
        base_schema = runs[0].schema_version
        for r in runs[1:]:
            if r.scenario_type != base_scenario:
                raise IncompatibleRunComparisonError(
                    f"Run {r.run_id} scenario type ({r.scenario_type}) does not match baseline ({base_scenario})"
                )
            if r.schema_version != base_schema:
                raise IncompatibleRunComparisonError(
                    f"Run {r.run_id} schema version ({r.schema_version}) does not match baseline ({base_schema})"
                )

        comparisons = []
        for r in runs:
            sc_data = json.loads(r.scorecard_json) if r.scorecard_json else None
            cfg_data = json.loads(r.config_json)
            comparisons.append(
                {
                    "run_id": r.run_id,
                    "status": r.status,
                    "scenario_type": r.scenario_type,
                    "seed": r.seed,
                    "total_ticks": r.total_ticks,
                    "speed_multiplier": r.speed_multiplier,
                    "config": cfg_data,
                    "scorecard": sc_data,
                }
            )

        return {
            "comparison_id": f"comp_{uuid.uuid4().hex[:8]}",
            "compatible": True,
            "disclaimer": DISCLAIMER_TEXT,
            "runs": comparisons,
        }

    def export_run_report(
        self, run_id: str, export_format: str = "json"
    ) -> dict[str, Any] | str:
        """Export comprehensive simulation run report with prominent synthetic disclaimer."""
        run = self.repo.get_run(run_id)
        if not run:
            raise ValueError(f"Simulation run {run_id} not found")

        ticks = self.repo.list_ticks(run_id, limit=3600)
        config_data = json.loads(run.config_json)
        scorecard_data = json.loads(run.scorecard_json) if run.scorecard_json else None

        report_data = {
            "report_id": f"rep_{run.run_id}",
            "disclaimer": DISCLAIMER_TEXT,
            "run_metadata": {
                "run_id": run.run_id,
                "status": run.status,
                "scenario_type": run.scenario_type,
                "scenario_version": run.scenario_version,
                "model_version": run.model_version,
                "schema_version": run.schema_version,
                "simulator_version": run.simulator_version,
                "seed": run.seed,
                "total_ticks": run.total_ticks,
                "current_tick": run.current_tick,
                "speed_multiplier": run.speed_multiplier,
                "created_at": run.created_at,
                "updated_at": run.updated_at,
                "completed_at": run.completed_at,
            },
            "configuration": config_data,
            "scorecard": scorecard_data,
            "tick_summary": [
                {
                    "tick": t.tick,
                    "offered_legit_pps": t.offered_legit_pps,
                    "offered_attack_pps": t.offered_attack_pps,
                    "served_legit_pps": t.served_legit_pps,
                    "dropped_legit_pps": t.dropped_legit_pps,
                    "dropped_attack_pps": t.dropped_attack_pps,
                    "latency_ms": t.latency_ms,
                    "availability_pct": t.availability_pct,
                    "prediction": t.prediction,
                    "policy_action": t.policy_action,
                }
                for t in ticks
            ],
        }

        if export_format.lower() == "markdown":
            return self._format_markdown_report(report_data)

        if export_format.lower() == "csv":
            return self._format_csv_report(report_data)

        return report_data

    def _format_csv_report(self, data: dict[str, Any]) -> str:
        lines = [
            "tick,offered_legit_pps,offered_attack_pps,served_legit_pps,dropped_legit_pps,dropped_attack_pps,latency_ms,availability_pct,prediction,policy_action"
        ]
        for t in data.get("tick_summary", []):
            lines.append(
                f"{t['tick']},{t['offered_legit_pps']},{t['offered_attack_pps']},{t['served_legit_pps']},{t['dropped_legit_pps']},{t['dropped_attack_pps']},{t['latency_ms']},{t['availability_pct']},{t['prediction']},{t['policy_action']}"
            )
        return "\n".join(lines)

    def _format_markdown_report(self, data: dict[str, Any]) -> str:
        meta = data["run_metadata"]
        sc = data.get("scorecard") or {}
        lines = [
            f"# SENTRIX Simulation Run Report: `{meta['run_id']}`",
            "",
            f"> **{data['disclaimer']}**",
            "",
            "## Run Metadata",
            f"- **Scenario Type:** `{meta['scenario_type']}`",
            f"- **Random Seed:** `{meta['seed']}`",
            f"- **Status:** `{meta['status']}`",
            f"- **Progress:** `{meta['current_tick']}/{meta['total_ticks']}` ticks",
            f"- **Simulator Version:** `{meta['simulator_version']}`",
            f"- **Model Version:** `{meta['model_version']}`",
            "",
            "## Scorecard Summary",
        ]
        if sc:
            lines.extend(
                [
                    f"- **Time-to-Detect:** {sc.get('time_to_detect_seconds')} seconds",
                    f"- **Time-to-Mitigate:** {sc.get('time_to_mitigate_seconds')} seconds",
                    f"- **Attack Traffic Blocked:** {sc.get('attack_traffic_blocked_pct')}%",
                    f"- **Collateral Legitimate Drop:** {sc.get('collateral_legitimate_pct')}%",
                    f"- **Downtime Seconds:** {sc.get('downtime_seconds')}s",
                    f"- **Average Availability:** {sc.get('average_availability_pct')}%",
                    f"- **Average Latency:** {sc.get('average_latency_ms')} ms",
                    f"- **Precision:** {sc.get('precision')}",
                    f"- **Recall:** {sc.get('recall')}",
                    f"- **False-Positive Rate:** {sc.get('false_positive_rate')}",
                ]
            )
        else:
            lines.append("*(Scorecard not yet available)*")

        lines.extend(
            [
                "",
                f"## Committed Ticks: {len(data['tick_summary'])} ticks recorded.",
            ]
        )
        return "\n".join(lines)
