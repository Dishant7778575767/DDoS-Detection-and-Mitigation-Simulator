"""Scenario definitions, typed parameters, and ground-truth schemas."""

from __future__ import annotations

import ipaddress
from enum import Enum

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator


class ScenarioType(str, Enum):
    """Supported deterministic scenario profiles."""

    SYN_FLOOD = "syn_flood"
    UDP_FLOOD = "udp_flood"
    HTTP_FLOOD = "http_flood"
    LOW_AND_SLOW = "low_and_slow"
    MIXED = "mixed"
    FLASH_CROWD = "flash_crowd"


class GroundTruth(BaseModel):
    """Ground truth metadata tracked separately from feature vectors."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    tick: int = Field(..., ge=0, description="Virtual tick index")
    is_attack: bool = Field(
        ..., description="Whether traffic in this tick constitutes an attack"
    )
    attack_type: ScenarioType | None = Field(
        default=None,
        description="Active attack scenario type, or None for benign/flash-crowd",
    )
    attack_pps: float = Field(
        default=0.0, ge=0.0, description="Portion of PPS generated by attacker"
    )
    legitimate_pps: float = Field(
        default=0.0, ge=0.0, description="Portion of PPS generated by legitimate users"
    )
    total_pps: float = Field(
        default=0.0, ge=0.0, description="Aggregate observed packets per second"
    )
    label: str = Field(
        ...,
        description="Ground truth class name ('BENIGN', 'SynFlood', 'UDPFlood', etc.)",
    )


class ScenarioConfig(BaseModel):
    """Validated configuration parameters for a deterministic simulation run."""

    model_config = ConfigDict(extra="forbid")

    scenario_type: ScenarioType = Field(
        default=ScenarioType.SYN_FLOOD,
        description="Type of traffic scenario to simulate",
    )
    scenario_version: str = Field(
        default="1.0.0",
        description="Scenario engine schema version",
    )
    seed: int = Field(
        default=42,
        ge=0,
        le=4_294_967_295,  # 32-bit unsigned integer bound
        description="PRNG integer seed ensuring deterministic reproduction",
    )
    duration_seconds: int = Field(
        default=60,
        ge=10,
        le=300,
        description="Total duration of the simulation in virtual seconds",
    )
    tick_interval: float = Field(
        default=1.0,
        ge=0.5,
        le=5.0,
        description="Length of one virtual tick in seconds",
    )
    target_ip: str = Field(
        default="10.0.0.50",
        description="Destination IPv4 or IPv6 address for the virtual victim",
    )
    target_port: int = Field(
        default=80,
        ge=1,
        le=65535,
        description="Destination port on virtual victim",
    )
    baseline_pps: float = Field(
        default=200.0,
        ge=10.0,
        le=2000.0,
        description="Normal background legitimate traffic rate in packets/sec",
    )
    attack_peak_pps: float = Field(
        default=10_000.0,
        ge=500.0,
        le=100_000.0,
        description="Peak traffic rate reached during attack or surge window",
    )
    attack_start_tick: int = Field(
        default=10,
        ge=1,
        description="Tick at which the attack or surge traffic starts",
    )
    attack_end_tick: int = Field(
        default=50,
        ge=1,
        description="Tick at which the attack or surge traffic terminates",
    )

    @field_validator("target_ip")
    @classmethod
    def validate_target_ip(cls, val: str) -> str:
        cleaned = val.strip()
        try:
            ipaddress.ip_address(cleaned)
        except ValueError as err:
            raise ValueError(
                f"'{cleaned}' is not a valid IPv4 or IPv6 address"
            ) from err
        return cleaned

    @model_validator(mode="after")
    def validate_tick_bounds(self) -> ScenarioConfig:
        total_ticks = int(self.duration_seconds / self.tick_interval)
        if self.attack_start_tick > self.attack_end_tick:
            raise ValueError(
                f"attack_start_tick ({self.attack_start_tick}) cannot be greater "
                f"than attack_end_tick ({self.attack_end_tick})"
            )
        if self.attack_end_tick > total_ticks:
            raise ValueError(
                f"attack_end_tick ({self.attack_end_tick}) exceeds total run ticks ({total_ticks})"
            )
        return self

    @property
    def total_ticks(self) -> int:
        return int(self.duration_seconds / self.tick_interval)
