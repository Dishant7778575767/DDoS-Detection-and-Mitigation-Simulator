class SimulationRunRepository:
    """Repository managing persistent simulation runs, per-tick records, and scorecard state."""

    def __init__(self, session: Session) -> None:
        self.session = session

    def create_run(
        self,
        run_id: str,
        scenario_type: str,
        seed: int,
        total_ticks: int,
        config: dict,
        scenario_version: str = "1.0.0",
        model_version: str = "rf-1.0.0",
        schema_version: str = "1.0.0",
        simulator_version: str = "1.5.0",
        speed_multiplier: float = 1.0,
    ) -> SimulationRunModel:
        now = _current_timestamp()
        run = SimulationRunModel(
            run_id=run_id,
            scenario_type=scenario_type,
            scenario_version=scenario_version,
            model_version=model_version,
            schema_version=schema_version,
            simulator_version=simulator_version,
            seed=seed,
            total_ticks=total_ticks,
            current_tick=0,
            speed_multiplier=speed_multiplier,
            status="created",
            config_json=json.dumps(config),
            scorecard_json=None,
            created_at=now,
            updated_at=now,
        )
        self.session.add(run)
        self.session.commit()
        self.session.refresh(run)
        return run

    def get_run(self, run_id: str) -> SimulationRunModel | None:
        stmt = select(SimulationRunModel).where(SimulationRunModel.run_id == run_id)
        return self.session.scalars(stmt).first()

    def list_runs(
        self,
        status: str | None = None,
        limit: int = 50,
        offset: int = 0,
    ) -> list[SimulationRunModel]:
        stmt = select(SimulationRunModel)
        if status:
            stmt = stmt.where(SimulationRunModel.status == status)
        stmt = stmt.order_by(desc(SimulationRunModel.id)).offset(offset).limit(limit)
        return list(self.session.scalars(stmt).all())

    def count_runs(self, status: str | None = None) -> int:
        stmt = select(func.count(SimulationRunModel.id))
        if status:
            stmt = stmt.where(SimulationRunModel.status == status)
        return self.session.scalar(stmt) or 0

    def update_run_status(
        self,
        run_id: str,
        new_status: str,
        scorecard: dict | None = None,
        completed_at: str | None = None,
    ) -> SimulationRunModel | None:
        run = self.get_run(run_id)
        if not run:
            return None
        run.status = new_status
        run.updated_at = _current_timestamp()
        if scorecard is not None:
            run.scorecard_json = json.dumps(scorecard)
        if completed_at is not None:
            run.completed_at = completed_at
        self.session.commit()
        self.session.refresh(run)
        return run

    def update_run_tick(self, run_id: str, tick: int) -> None:
        run = self.get_run(run_id)
        if run:
            run.current_tick = tick
            run.updated_at = _current_timestamp()
            self.session.commit()

    def record_tick(
        self,
        run_id: str,
        tick: int,
        offered_legit_pps: float,
        offered_attack_pps: float,
        served_legit_pps: float,
        dropped_legit_pps: float,
        dropped_attack_pps: float,
        latency_ms: float,
        availability_pct: float,
        prediction: str,
        policy_action: str,
        active_mitigations_count: int = 0,
    ) -> SimulationTickModel:
        tick_model = SimulationTickModel(
            run_id=run_id,
            tick=tick,
            offered_legit_pps=offered_legit_pps,
            offered_attack_pps=offered_attack_pps,
            served_legit_pps=served_legit_pps,
            dropped_legit_pps=dropped_legit_pps,
            dropped_attack_pps=dropped_attack_pps,
            latency_ms=latency_ms,
            availability_pct=availability_pct,
            prediction=prediction,
            policy_action=policy_action,
            active_mitigations_count=active_mitigations_count,
            timestamp=_current_timestamp(),
        )
        self.session.add(tick_model)
        self.session.commit()
        self.session.refresh(tick_model)
        return tick_model

    def list_ticks(
        self,
        run_id: str,
        limit: int = 1000,
        offset: int = 0,
    ) -> list[SimulationTickModel]:
        stmt = (
            select(SimulationTickModel)
            .where(SimulationTickModel.run_id == run_id)
            .order_by(SimulationTickModel.tick.asc())
            .offset(offset)
            .limit(limit)
        )
        return list(self.session.scalars(stmt).all())

    def mark_interrupted_runs(self) -> int:
        """Mark any active or running runs as interrupted upon startup recovery."""
        stmt = select(SimulationRunModel).where(
            SimulationRunModel.status.in_(["running", "created"])
        )
        runs = list(self.session.scalars(stmt).all())
        now = _current_timestamp()
        for r in runs:
            r.status = "interrupted"
            r.updated_at = now
        if runs:
            self.session.commit()
        return len(runs)

    def cleanup_old_runs(self, keep_max: int = 50) -> int:
        """Enforce retention limits by pruning oldest terminal runs when total exceeds keep_max."""
        total = self.count_runs()
        if total <= keep_max:
            return 0
        excess = total - keep_max
        stmt = (
            select(SimulationRunModel)
            .where(
                SimulationRunModel.status.in_(["completed", "cancelled", "interrupted"])
            )
            .order_by(SimulationRunModel.id.asc())
            .limit(excess)
        )
        old_runs = list(self.session.scalars(stmt).all())
        for r in old_runs:
            self.session.delete(r)
        self.session.commit()
        return len(old_runs)


class CloudFrontKinesisRepository:
    """Repository for managing CloudFront Kinesis event deduplication and retention."""

    def __init__(self, session: Session) -> None:
        self.session = session

    def record_events_batch(
        self,
        events: list[tuple[str, str, str, str, str]],
    ) -> tuple[list[str], int]:
        """Record batch of events with savepoint deduplication.

        events is a list of tuples: (request_id, timestamp, stream_name, shard_id, sequence_number).
        Returns (list_of_accepted_request_ids, duplicate_count).
        """
        now = _current_timestamp()
        accepted_ids: list[str] = []
        duplicate_count = 0

        for req_id, ts, stream, shard, seq in events:
            savepoint = self.session.begin_nested()
            self.session.add(
                CloudFrontKinesisEventModel(
                    request_id=req_id,
                    timestamp=ts,
                    received_at=now,
                    stream_name=stream,
                    shard_id=shard,
                    sequence_number=seq,
                )
            )
            try:
                savepoint.commit()
                accepted_ids.append(req_id)
            except IntegrityError:
                savepoint.rollback()
                duplicate_count += 1

        self.session.commit()
        return accepted_ids, duplicate_count

    def prune_older_than(self, older_than_iso: str) -> int:
        """Prune deduplication records older than cutoff timestamp."""
        stmt = select(CloudFrontKinesisEventModel).where(
            CloudFrontKinesisEventModel.timestamp < older_than_iso
        )
        old_records = list(self.session.scalars(stmt).all())
        for r in old_records:
            self.session.delete(r)
        if old_records:
            self.session.commit()
        return len(old_records)


class KinesisCheckpointRepository:
    """Repository for managing persistent stream consumption checkpoints per shard."""

    def __init__(self, session: Session) -> None:
        self.session = session

    def get_checkpoint(self, stream_name: str, shard_id: str) -> str | None:
        """Fetch the latest committed sequence number for a stream shard."""
        stmt = select(KinesisCheckpointModel).where(
            KinesisCheckpointModel.stream_name == stream_name,
            KinesisCheckpointModel.shard_id == shard_id,
        )
        record = self.session.scalars(stmt).first()
        return record.last_sequence_number if record else None

    def update_checkpoint(
        self,
        stream_name: str,
        shard_id: str,
        sequence_number: str,
        records_processed_delta: int = 0,
    ) -> KinesisCheckpointModel:
        """Upsert the committed sequence number checkpoint for a stream shard."""
        stmt = select(KinesisCheckpointModel).where(
            KinesisCheckpointModel.stream_name == stream_name,
            KinesisCheckpointModel.shard_id == shard_id,
        )
        record = self.session.scalars(stmt).first()
        now = _current_timestamp()
        if record is None:
            record = KinesisCheckpointModel(
                stream_name=stream_name,
                shard_id=shard_id,
                last_sequence_number=sequence_number,
                records_processed=records_processed_delta,
                updated_at=now,
            )
            self.session.add(record)
        else:
            record.last_sequence_number = sequence_number
            record.records_processed += records_processed_delta
            record.updated_at = now

        self.session.commit()
        self.session.refresh(record)
        return record

    def list_checkpoints(self, stream_name: str) -> list[KinesisCheckpointModel]:
        """List all shard checkpoints for a stream."""
        stmt = (
            select(KinesisCheckpointModel)
            .where(KinesisCheckpointModel.stream_name == stream_name)
            .order_by(KinesisCheckpointModel.shard_id.asc())
        )
        return list(self.session.scalars(stmt).all())
