class AlertRepository:
    def __init__(self, session: Session) -> None:
        self.session = session

    def create(
        self,
        detection_id: int | None,
        severity: str,
        title: str,
        description: str,
        source_id: str,
        timestamp: str,
    ) -> AlertModel:
        alert = AlertModel(
            alert_id=f"alt_{uuid4().hex[:12]}",
            detection_id=detection_id,
            severity=severity,
            title=title,
            description=description,
            source_id=source_id,
            timestamp=timestamp,
            status="active",
        )
        self.session.add(alert)
        self.session.commit()
        self.session.refresh(alert)
        return alert

    def get_by_id(self, alert_id: str) -> AlertModel | None:
        stmt = select(AlertModel).where(AlertModel.alert_id == alert_id)
        return self.session.scalars(stmt).first()

    def resolve_alerts_for_run(self, run_id: str) -> int:
        """Mark all alerts generated by a specific simulation run as resolved."""
        stmt = (
            update(AlertModel)
            .where(
                AlertModel.source_id.like(f"sim_{run_id}%"),
                AlertModel.status == "active",
            )
            .values(
                status="resolved",
            )
        )
        res = self.session.execute(stmt)
        if res.rowcount > 0:
            self.session.commit()
        return res.rowcount

    def resolve_inactive_simulation_alerts(self) -> int:
        """Automatically resolve alerts from simulations that have completed, cancelled, or are no longer actively running."""
        active_runs_stmt = select(SimulationRunModel.run_id).where(
            SimulationRunModel.status == "running"
        )
        running_run_ids = list(self.session.scalars(active_runs_stmt).all())

        stmt = (
            update(AlertModel)
            .where(
                AlertModel.source_id.like("sim_%"),
                AlertModel.status == "active",
            )
            .values(
                status="resolved",
            )
        )
        if running_run_ids:
            for r_id in running_run_ids:
                stmt = stmt.where(~AlertModel.source_id.like(f"sim_{r_id}%"))
        res = self.session.execute(stmt)
        if res.rowcount > 0:
            self.session.commit()
        return res.rowcount

    def list_filtered(
        self,
        severity: str | None = None,
        status: str | None = None,
        limit: int = 50,
        offset: int = 0,
        target_ip: str | None = None,
    ) -> list[AlertModel]:
        self.resolve_inactive_simulation_alerts()
        stmt = select(AlertModel)
        if severity:
            sev_clean = severity.lower().strip()
            if sev_clean == "high":
                stmt = stmt.where(AlertModel.severity.in_(["high", "warning"]))
            elif sev_clean == "low":
                stmt = stmt.where(AlertModel.severity.in_(["low", "info"]))
            else:
                stmt = stmt.where(func.lower(AlertModel.severity) == sev_clean)
        if status:
            stmt = stmt.where(AlertModel.status == status)
        if target_ip:
            stmt = stmt.where(
                AlertModel.detection.has(
                    DetectionModel.observation.has(
                        func.lower(ObservationModel.target_ip) == target_ip.lower()
                    )
                )
            )
        stmt = stmt.order_by(desc(AlertModel.id)).offset(offset).limit(limit)
        return list(self.session.scalars(stmt).all())

    def count_filtered(
        self,
        severity: str | None = None,
        status: str | None = None,
        target_ip: str | None = None,
    ) -> int:
        self.resolve_inactive_simulation_alerts()
        stmt = select(func.count(AlertModel.id))
        if severity:
            sev_clean = severity.lower().strip()
            if sev_clean == "high":
                stmt = stmt.where(AlertModel.severity.in_(["high", "warning"]))
            elif sev_clean == "low":
                stmt = stmt.where(AlertModel.severity.in_(["low", "info"]))
            else:
                stmt = stmt.where(func.lower(AlertModel.severity) == sev_clean)
        if status:
            stmt = stmt.where(AlertModel.status == status)
        if target_ip:
            stmt = stmt.where(
                AlertModel.detection.has(
                    DetectionModel.observation.has(
                        func.lower(ObservationModel.target_ip) == target_ip.lower()
                    )
                )
            )
        return self.session.scalar(stmt) or 0


class MitigationRepository:
    def __init__(self, session: Session) -> None:
        self.session = session

    def expire_stale_mitigations(self) -> int:
        """Find any active, simulated, or applied mitigations whose expires_at is past and mark them expired."""
        now_iso = _current_timestamp()
        stmt = (
            update(MitigationModel)
            .where(
                MitigationModel.status.in_(
                    ["proposed", "simulated", "active", "applied"]
                ),
                MitigationModel.expires_at.is_not(None),
                MitigationModel.expires_at <= now_iso,
            )
            .values(
                status="expired",
                updated_at=now_iso,
            )
        )
        res = self.session.execute(stmt)
        if res.rowcount > 0:
            self.session.commit()
        return res.rowcount

    def create(
        self,
        detection_id: int | None,
        target_ip: str,
        target_port: int | None,
        action_type: str,
        rate_limit_pps: int,
        duration_seconds: int,
        status: str = "proposed",
        mode: str = "simulation",
        action_id: str | None = None,
        expires_at: str | None = None,
    ) -> MitigationModel:
        now = _current_timestamp()
        mitigation = MitigationModel(
            action_id=action_id or f"act_{uuid4().hex[:12]}",
            detection_id=detection_id,
            target_ip=target_ip,
            target_port=target_port,
            action_type=action_type,
            rate_limit_pps=rate_limit_pps,
            duration_seconds=duration_seconds,
            status=status,
            mode=mode,
            created_at=now,
            updated_at=now,
            expires_at=expires_at,
        )
        self.session.add(mitigation)
        self.session.commit()
        self.session.refresh(mitigation)
        return mitigation

    def get_by_action_id(self, action_id: str) -> MitigationModel | None:
        stmt = select(MitigationModel).where(MitigationModel.action_id == action_id)
        return self.session.scalars(stmt).first()

    def update_status(
        self,
        action_id: str,
        new_status: str,
        cancelled_at: str | None = None,
        expires_at: str | None = None,
    ) -> MitigationModel | None:
        mitigation = self.get_by_action_id(action_id)
        if not mitigation:
            return None
        mitigation.status = new_status
        mitigation.updated_at = _current_timestamp()
        if cancelled_at:
            mitigation.cancelled_at = cancelled_at
        if expires_at:
            mitigation.expires_at = expires_at
        self.session.commit()
        self.session.refresh(mitigation)
        return mitigation

    def list_filtered(
        self,
        status: str | None = None,
        mode: str | None = None,
        limit: int = 50,
        offset: int = 0,
    ) -> list[MitigationModel]:
        self.expire_stale_mitigations()
        stmt = select(MitigationModel)
        if status:
            stmt = stmt.where(MitigationModel.status == status)
        if mode:
            stmt = stmt.where(MitigationModel.mode == mode)
        stmt = stmt.order_by(desc(MitigationModel.id)).offset(offset).limit(limit)
        return list(self.session.scalars(stmt).all())

    def count_filtered(
        self,
        status: str | None = None,
        mode: str | None = None,
    ) -> int:
        self.expire_stale_mitigations()
        stmt = select(func.count(MitigationModel.id))
        if status:
            stmt = stmt.where(MitigationModel.status == status)
        if mode:
            stmt = stmt.where(MitigationModel.mode == mode)
        return self.session.scalar(stmt) or 0

    def expire_simulation_mitigations(self) -> int:
        """Expire all active or simulated mitigations that were created by the simulator."""
        now_iso = _current_timestamp()
        stmt = (
            update(MitigationModel)
            .where(
                MitigationModel.mode == "simulation",
                MitigationModel.status.in_(
                    ["proposed", "simulated", "active", "applied"]
                ),
            )
            .values(
                status="expired",
                updated_at=now_iso,
            )
        )
        res = self.session.execute(stmt)
        if res.rowcount > 0:
            self.session.commit()
        return res.rowcount

    def get_active_or_simulated(self) -> list[MitigationModel]:
        stmt = (
            select(MitigationModel)
            .where(
                MitigationModel.status.in_(
                    ["proposed", "simulated", "active", "applied"]
                )
            )
            .order_by(desc(MitigationModel.id))
        )
        return list(self.session.scalars(stmt).all())


class ThresholdConfigRepository:
    def __init__(self, session: Session) -> None:
        self.session = session

    def get_active(self) -> ThresholdConfigModel:
        stmt = (
            select(ThresholdConfigModel)
            .where(ThresholdConfigModel.is_active.is_(True))
            .order_by(desc(ThresholdConfigModel.id))
        )
        config = self.session.scalars(stmt).first()
        if not config:
            config = ThresholdConfigModel(
                version="v1.0.0",
                is_active=True,
                pps_threshold=5000.0,
                bps_threshold=10_000_000.0,
                syn_pps_threshold=500.0,
                syn_ack_ratio_threshold=5.0,
                rf_probability_threshold=0.75,
                iforest_score_threshold=0.2664,
                updated_by="system",
                created_at=_current_timestamp(),
            )
            self.session.add(config)
            self.session.commit()
            self.session.refresh(config)
        return config

    def update(self, updated_by: str, updates: dict) -> ThresholdConfigModel:
        current = self.get_active()
        current.is_active = False

        new_version = f"v{uuid4().hex[:6]}"
        new_config = ThresholdConfigModel(
            version=new_version,
            is_active=True,
            pps_threshold=float(updates.get("pps_threshold", current.pps_threshold)),
            bps_threshold=float(updates.get("bps_threshold", current.bps_threshold)),
            syn_pps_threshold=float(
                updates.get("syn_pps_threshold", current.syn_pps_threshold)
            ),
            syn_ack_ratio_threshold=float(
                updates.get("syn_ack_ratio_threshold", current.syn_ack_ratio_threshold)
            ),
            rf_probability_threshold=float(
                updates.get(
                    "rf_probability_threshold", current.rf_probability_threshold
                )
            ),
            iforest_score_threshold=float(
                updates.get("iforest_score_threshold", current.iforest_score_threshold)
            ),
            updated_by=updated_by,
            created_at=_current_timestamp(),
        )
        self.session.add(new_config)
        self.session.commit()
        self.session.refresh(new_config)
        return new_config


